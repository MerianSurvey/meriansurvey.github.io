#!/usr/bin/env python3
"""Make the filter data of the site: data/filters.js, data/filter-shifts.js and the curves in downloads/.

Usage:
    python3 tools/make_filters.py <Merian filter directory> <HSC filter directory>

The Merian directory holds Transmission_curves_N540.fits and Transmission_curves_N708.fits, the
laboratory transmission of each filter measured by Asahi Spectra at 49 positions (parallel beam,
5 deg angle of incidence, transmission in percent, columns "Location 1" to "Location 49").
The HSC directory holds HSC_FILTER_{g,r2,i2,z,Y}.txt (wavelength in Angstrom, filter transmission).
Needs numpy and astropy.
"""
import argparse
import json
import os

import numpy as np
from astropy.io import fits

SITE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
# Positions along the +X axis of the manufacturer's measurement map, at 0, 150, 200, 250 and 280 mm
# from the filter center (the five curves of Fig. 13 in Luo et al. 2024).
AXIS_POSITIONS = [(1, 0), (6, 150), (14, 200), (26, 250), (34, 280)]
RINGS = [100, 150, 200, 250, 280]   # mm, radii of the measurement rings
SHIFT_WINDOW = {'N540': (517, 563), 'N708': (687, 733)}   # nm, the same 46 nm span for both


def edges(wl, T):
    fine = np.arange(wl[0], wl[-1], 0.05)
    Tf = np.interp(fine, wl, T)
    m = Tf >= Tf.max() / 2
    return round(float(fine[m][0]), 1), round(float(fine[m][-1]), 1)


def half_max_crossings(wl, T):
    """Wavelengths where the curve crosses half its maximum, linearly interpolated."""
    half = 0.5 * T.max()
    above = np.flatnonzero(T >= half)
    i0, i1 = above[0], above[-1]
    lo = np.interp(half, [T[i0 - 1], T[i0]], [wl[i0 - 1], wl[i0]])
    hi = np.interp(half, [T[i1 + 1], T[i1]], [wl[i1 + 1], wl[i1]])
    return lo, hi


def half_max_center(wl, T):
    """Midpoint and separation of the two half-maximum crossings."""
    lo, hi = half_max_crossings(wl, T)
    return 0.5 * (lo + hi), hi - lo


def read_merian(path):
    d = fits.open(path)[1].data
    wl = np.round(np.asarray(d['Wavelength[nm]'], float), 1)
    T = np.array([np.asarray(d[f'Location {k}'], float) for k in range(1, 50)]) / 100.0
    o = np.argsort(wl)
    return wl[o], T[:, o]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('merian_dir')
    ap.add_argument('hsc_dir')
    args = ap.parse_args()

    out, shifts, merian = {}, {'radii': [r for _, r in AXIS_POSITIONS], 'rings': RINGS}, {}

    # Merian medium bands: unweighted mean of the 49 lab measurements, 1 nm sampling (home-page figure).
    for name, lo, hi in [('N540', 515, 565), ('N708', 680, 735)]:
        wl, T49 = read_merian(os.path.join(args.merian_dir, f'Transmission_curves_{name}.fits'))
        merian[name] = (wl, T49)
        T = T49.mean(axis=0)
        grid = np.arange(lo, hi + 0.01, 1.0)
        a, b = edges(wl, T)
        out[name] = {'wl': [round(float(x), 1) for x in grid], 'T': [round(float(x), 4) for x in np.interp(grid, wl, T)],
                     'half_lo': a, 'half_hi': b}

    # HSC broad bands (filter transmission), 2 nm sampling. The keys r and i are the r2 and i2 filters.
    for key, fn in [('g', 'HSC_FILTER_g.txt'), ('r', 'HSC_FILTER_r2.txt'), ('i', 'HSC_FILTER_i2.txt'),
                    ('z', 'HSC_FILTER_z.txt'), ('y', 'HSC_FILTER_Y.txt')]:
        arr = np.loadtxt(os.path.join(args.hsc_dir, fn))
        wl = arr[:, 0] / 10.0
        T = np.clip(arr[:, 1], 0, None)
        o = np.argsort(wl)
        wl, T = wl[o], T[o]
        if T.max() > 1.5:
            T = T / 100.0
        good = np.where(T > 0.01 * T.max())[0]
        lo, hi = np.floor(wl[good[0]] / 2) * 2, np.ceil(wl[good[-1]] / 2) * 2
        grid = np.arange(lo, hi + 0.01, 2.0)
        a, b = edges(wl, T)
        out[key] = {'wl': [round(float(x), 1) for x in grid], 'T': [round(float(x), 4) for x in np.interp(grid, wl, T)],
                    'half_lo': a, 'half_hi': b}
        print(f'{key} ({fn}): {lo:.0f}-{hi:.0f} nm, peak {T.max():.3f}, half maximum {a}-{b} nm')

    js = ('// Filter transmission curves, drawn on the home page and on the Filters page.\n'
          '// N540, N708: unweighted mean of the 49 laboratory measurements across each Merian filter, 1 nm sampling.\n'
          '// g, r, i, z, y: HSC g, r2, i2, z and y filter transmission curves, 2 nm sampling.\n'
          '// wl = wavelength in nm, T = transmission (0 to 1), half_lo / half_hi = half-maximum edges in nm.\n'
          '// Generated by tools/make_filters.py. Do not edit by hand.\n'
          'window.MERIAN_FILTERS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    with open(os.path.join(SITE, 'data', 'filters.js'), 'w') as fh:
        fh.write(js)

    # Curves at five distances from the filter center, for the Filters page.
    for name, (wl, T49) in merian.items():
        w0, w1 = SHIFT_WINDOW[name]
        m = (wl >= w0 - 1e-6) & (wl <= w1 + 1e-6)
        curves = [T49[loc - 1] for loc, _ in AXIS_POSITIONS]
        centers = [round(float(half_max_center(wl, c)[0]), 2) for c in curves]
        shifts[name] = {'window': [w0, w1], 'wl0': float(wl[m][0]), 'step': 0.2,
                        'T': [[round(float(v) * 100, 1) for v in c[m]] for c in curves],
                        'center': centers}
        print(f'{name}: centers {centers} nm, shift center to 280 mm {centers[-1] - centers[0]:+.2f} nm')
    js = ('// Laboratory transmission (percent) of N540 and N708 at the filter center and at 150, 200, 250 and\n'
          '// 280 mm from it, along one axis (Asahi Spectra measurements at positions 1, 6, 14, 26 and 34).\n'
          '// T[k][j] is the curve at radii[k], at wavelength wl0 + j * step nm. center = half-maximum center (nm).\n'
          '// Generated by tools/make_filters.py. Do not edit by hand.\n'
          'window.MERIAN_FILTER_SHIFTS = ' + json.dumps(shifts, separators=(',', ':')) + ';\n')
    with open(os.path.join(SITE, 'data', 'filter-shifts.js'), 'w') as fh:
        fh.write(js)

    # Downloadable mean curves at the measured 0.2 nm sampling.
    os.makedirs(os.path.join(SITE, 'downloads'), exist_ok=True)
    for name, (wl, T49) in merian.items():
        T = T49.mean(axis=0)
        lo, hi = half_max_crossings(wl, T)
        center, fwhm = 0.5 * (lo + hi), hi - lo
        line = {'N540': '[O III]', 'N708': 'H-alpha'}[name]
        path = os.path.join(SITE, 'downloads', f'merian_{name}_transmission.csv')
        with open(path, 'w') as fh:
            fh.write(f'# Merian {name} medium-band filter (Dark Energy Camera), laboratory transmission.\n'
                     f'# Unweighted mean of the measurements by Asahi Spectra at 49 positions on the filter,\n'
                     f'# in a parallel beam at 5 degrees angle of incidence. Filter transmission only, without the\n'
                     f'# telescope, the camera, the detector or the atmosphere.\n'
                     f'# Half maximum at {lo:.1f} and {hi:.1f} nm (center {center:.1f} nm, width {fwhm:.1f} nm). Designed for {line}.\n'
                     f'# Reference: Luo et al. 2024, MNRAS 530, 4988 (doi:10.1093/mnras/stae925).\n'
                     'wavelength_nm,transmission\n')
            for x, y in zip(wl, T):
                fh.write(f'{x:.1f},{y:.5f}\n')
        print(f'wrote {os.path.relpath(path, SITE)}: center {center:.2f} nm, FWHM {fwhm:.2f} nm, min {T.min():.5f}')


if __name__ == '__main__':
    main()
